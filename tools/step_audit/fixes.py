"""Fix proposals for proven-shape findings and the generated binding files (game/pacing_fixes.inc, hle_map/uc.cfg blocks)."""
from dataclasses import dataclass
from pathlib import Path
import re

BEGIN, END = "# BEGIN step_audit", "# END step_audit"


@dataclass(frozen=True)
class FixRecord:
    entry: str
    frame: int
    lr: str
    template: str          # scale | scale_ret | pow_alpha
    operand: str           # "f1".."f4"
    power: int
    evidence: str


@dataclass(frozen=True)
class Rejected:
    function: str
    store: int | None
    pattern: str
    reason: str


def _callers(prog, function, operand, k):
    lrs = set()
    for (caller, _), result in prog.results.items():
        for call in result.calls:
            direct = call.callee == function
            virtual = call.slot is not None and function in prog_slot_targets(prog, call.slot)
            if (direct or virtual) and call.args.get(operand) is not None and call.args[operand].k == k:
                lrs.add(f"{call.address + 4:08X}")
    return sorted(lrs)


def prog_slot_targets(prog, slot):
    index = getattr(prog, "dump_index", None)
    return index.slot_targets(slot) if index else set()


def propose(findings, prog):
    """Records only for exact P2 findings whose second step factor is an FPR argument of a function with a lowered-able prologue."""
    records, rejected = [], []
    for f in findings:
        if f.covered_by:
            rejected.append(Rejected(f.function, f.store, f.pattern, f"covered by {f.covered_by}"))
            continue
        if f.pattern != "P2" or f.confidence != "high":
            rejected.append(Rejected(f.function, f.store, f.pattern, "no automatic template for this pattern/confidence"))
            continue
        args = sorted(s[4:] for s in f.sources if s.startswith("arg:f"))
        if not args:
            rejected.append(Rejected(f.function, f.store, f.pattern, "step factor does not cross a call boundary as an FPR argument"))
            continue
        frame = prog.functions[f.function].prologue_frame if f.function in prog.functions else None
        if not frame:
            rejected.append(Rejected(f.function, f.store, f.pattern, "entry has no stwu prologue to lower"))
            continue
        operand = args[0]
        lrs = _callers(prog, f.function, operand, 1)
        if not lrs:
            rejected.append(Rejected(f.function, f.store, f.pattern, f"no caller passes a k=1 {operand}"))
            continue
        for lr in lrs:
            records.append(FixRecord(f.function, frame, lr, "scale", operand, -1,
                                     f"P2 store {f.store:08X} field {f.field}"))
    unique = {(r.entry, r.lr): r for r in records}
    return sorted(unique.values(), key=lambda r: (r.entry, r.lr)), rejected


def write_inc(records, path: Path):
    lines = ["// Generated by python -I tools/step_audit --apply; do not edit by hand.",
             "// PACING_ENTRY(entry, prologue frame) binds hle_PacingFix_<entry>; PACING_FIX(entry, caller LR, template, FPR, power of s)."]
    for entry in sorted({r.entry for r in records}):
        frame = next(r.frame for r in records if r.entry == entry)
        lines.append(f"PACING_ENTRY(0x{entry}, {frame})")
    for r in records:
        lines.append(f"PACING_FIX(0x{r.entry}, 0x{r.lr}, {r.template}, {int(r.operand[1:])}, {r.power})  // {r.evidence}")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def _replace_block(path: Path, body):
    text = Path(path).read_text(encoding="utf-8")
    block = "\n".join([BEGIN, *body, END]) + "\n"
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
    text = pattern.sub(lambda _: block, text) if pattern.search(text) else (text if text.endswith("\n") or not text else text + "\n") + block
    Path(path).write_text(text, encoding="utf-8")


def sync_bindings(records, hle_map: Path, uc_cfg: Path):
    entries = sorted({r.entry for r in records})
    _replace_block(hle_map, [f"@{e} PacingFix_0x{e}" for e in entries])
    _replace_block(uc_cfg, [f"entry {int(e, 16) + 4:08X}" for e in entries])
