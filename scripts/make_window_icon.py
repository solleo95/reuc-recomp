"""Writes common/window_icon_data.h: the 64x64 frame of assets/icon.ico as RGBA bytes, for SDL_SetWindowIcon on Linux (Windows takes the icon from app.rc).

Run again when assets/icon.ico changes:  python scripts/make_window_icon.py
"""
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIZE = 64


def ico_frame(data, size):
    count = struct.unpack_from("<H", data, 4)[0]
    for i in range(count):
        width, _, _, _, _, _, length, offset = struct.unpack_from("<BBBBHHII", data, 6 + 16 * i)
        if (width or 256) == size:
            return data[offset:offset + length]
    raise SystemExit(f"no {size}x{size} frame in icon.ico")


def decode_png(png):
    """RGBA8 non-interlaced PNG (what icon.ico holds) -> (width, height, bytes)."""
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    pos, idat = 8, b""
    while pos < len(png):
        length, kind = struct.unpack_from(">I4s", png, pos)
        body = png[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            width, height, depth, colour, _, _, interlace = struct.unpack(">IIBBBBB", body)
            assert (depth, colour, interlace) == (8, 6, 0), "expected RGBA8, not interlaced"
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    raw, stride, rows, previous = zlib.decompress(idat), width * 4, [], bytearray(width * 4)
    for y in range(height):
        kind, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            left = line[x - 4] if x >= 4 else 0
            up = previous[x]
            upper_left = previous[x - 4] if x >= 4 else 0
            if kind == 1:
                line[x] = (line[x] + left) & 255
            elif kind == 2:
                line[x] = (line[x] + up) & 255
            elif kind == 3:
                line[x] = (line[x] + (left + up) // 2) & 255
            elif kind == 4:
                p = left + up - upper_left
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - upper_left)
                line[x] = (line[x] + (left if pa <= pb and pa <= pc else up if pb <= pc else upper_left)) & 255
        rows.append(bytes(line))
        previous = line
    return width, height, b"".join(rows)


width, height, pixels = decode_png(ico_frame((ROOT / "assets" / "icon.ico").read_bytes(), SIZE))
assert (width, height) == (SIZE, SIZE)
lines = [", ".join(f"0x{b:02x}" for b in pixels[i:i + 32]) for i in range(0, len(pixels), 32)]
(ROOT / "common" / "window_icon_data.h").write_text(
    "// Generated by scripts/make_window_icon.py from assets/icon.ico: the 64x64 RGBA window icon (Linux).\n#pragma once\n"
    f"constexpr int kWindowIconSize = {SIZE};\nconstexpr unsigned char kWindowIconPixels[] = {{\n    " + ",\n    ".join(lines) + "\n};\n",
    newline="\n",
)
