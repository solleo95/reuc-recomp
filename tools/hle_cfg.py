# Generates project/hle.cfg from hle_map.txt and signature / verified symbol lists.
# Usage: python -I tools/hle_cfg.py <project dir>
import re
import sys
from pathlib import Path

proj = Path(sys.argv[1])
names = {}  # sdk name -> [addresses]
for fn in ("identified_sdk.txt", "symbols.txt", "gx_symbols.txt"):
    p = proj / fn
    if not p.exists():
        continue
    for line in p.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) >= 2:
            names.setdefault(parts[1], []).append(int(parts[0], 16))

out, errors = [], []
for raw in (proj / "hle_map.txt").read_text(encoding="utf-8").splitlines():
    line = raw.split("#", 1)[0].strip()
    if not line:
        continue
    parts = line.split()
    if parts[0].startswith("@"):
        out.append("hle %08X %s" % (int(parts[0][1:], 16), parts[1]))
        continue
    hle = parts[1] if len(parts) > 1 else parts[0]
    if not re.fullmatch(r"[A-Za-z0-9_]+", hle):
        errors.append("bad HLE name %r" % hle)
        continue
    addrs = sorted(set(names.get(parts[0], [])))
    if not addrs:
        errors.append("SDK name %r not found in identified_sdk.txt / symbols.txt / gx_symbols.txt" % parts[0])
        continue
    if len(addrs) > 1:
        errors.append("SDK name %r is ambiguous (%s): map the right one as '@<address> <HleName>'" % (parts[0], ", ".join("%08X" % a for a in addrs)))
        continue
    for a in addrs:
        out.append("hle %08X %s  # %s" % (a, hle, parts[0]))
if errors:
    sys.stderr.write("\n".join(errors) + "\n")
    sys.exit(1)
(proj / "hle.cfg").write_text("# generated by tools/hle_cfg.py - do not edit\n" + "\n".join(out) + "\n", encoding="utf-8")
print("hle.cfg: %d entries" % len(out))
